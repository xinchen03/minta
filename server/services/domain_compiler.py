"""Domain Compiler — auto-compile Clinical Practice Guidelines into Decision Graphs.

Input: CPG text (PDF/Markdown/plain text)
Output: DecisionGraph (nested decision tree + priority paths + branch conditions)

Algorithm:
1. Expand structured lists ("any of the following:") into individual if-then rules
2. Segment sentences (jieba Chinese / regex English)
3. Parse each sentence for triggers, conditions, actions, negation, nesting depth
4. Build recursive decision tree with parent-child branching
5. Extract root-to-leaf priority paths
6. Compile DecisionGraph with full metadata

Core scientific contribution: knowledge engineer replaced by compiler.
Based on: ACT-R Production Compilation (Taatgen & Lee 2003)
"""
